test_that("renv renders keep a populated library from the same checkout", {
  skip_if(.is_test_select())
  skip_if(.is_test_cran())
  local_mocked_bindings(project = function(...) NULL, .package = "renv")
  project <- withr::local_tempdir()
  withr::local_envvar(c(RENV_PATHS_LIBRARY = NA, RENV_PATHS_LIBRARY_ROOT = NA,
                        RENV_PATHS_RENV = NA, RENV_PROFILE = NA,
                        R_USER_CACHE_DIR = withr::local_tempdir()))
  withr::local_dir(project)
  writeLines("directories: {cache: {path: _tmp}}", "_projr.yml")
  writeLines("{}", "renv.lock")
  analysis <- renv::paths$library(project = project)
  fs::dir_create(file.path(analysis, "example"))
  file.create("renv/activate.R")
  writeLines("Package: example", file.path(analysis, "example", "DESCRIPTION"))
  writeLines(c("Package: analysis", "Version: 1.2.3"), "DESCRIPTION")
  canonical <- renv::paths$library(project = project)
  # Older renv versions use the same library for both project types.
  skip_if(identical(analysis, canonical))
  fs::dir_create(file.path(canonical, "renv"))
  writeLines("Package: renv", file.path(canonical, "renv", "DESCRIPTION"))

  before <- .libPaths()
  withr::defer(.libPaths(before, include.site = FALSE))
  vars <- c("RENV_PATHS_LIBRARY", "R_LIBS_USER")
  withr::local_envvar(Sys.getenv(vars, unset = NA_character_, names = TRUE))
  env <- Sys.getenv(vars, unset = NA_character_)
  for (start in c(analysis, canonical)) {
    .libPaths(c(start, before), include.site = FALSE)
    libs <- .libPaths()
    restore <- .build_renv_library_start()
    expect_equal(.libPaths()[1], normalizePath(analysis, winslash = "/"))
    expect_equal(renv::paths$library(project = project), analysis)
    restore()
    expect_identical(.libPaths(), libs)
    expect_identical(Sys.getenv(vars, unset = NA_character_), env)
  }

  fs::dir_create(file.path(canonical, "another"))
  writeLines("Package: another", file.path(canonical, "another", "DESCRIPTION"))
  restore <- .build_renv_library_start()
  withr::defer(restore())
  expect_equal(.libPaths()[1], normalizePath(canonical, winslash = "/"))
  expect_false(analysis %in% .libPaths())
  writeLines("---", "report.Rmd")
  writeLines(c("directories: {cache: {path: _tmp}, docs: {path: docs}}",
               "build: {scripts: [report.Rmd]}"), "_projr.yml")
  files <- list.files(project, recursive = TRUE, all.files = TRUE)
  status <- projr_build_check_packages()
  expect_false(status$available)
  expect_true(all(c("knitr", "rmarkdown") %in% status$missing))
  expect_match(status$message, canonical, fixed = TRUE)
  expect_match(status$install_cmds, "renv::install", fixed = TRUE)
  expect_identical(list.files(project, recursive = TRUE, all.files = TRUE), files)
})
